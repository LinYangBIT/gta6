"""Export the original Blender environment and car to portable web assets.

blender -b scenes/sunset_coast.blend --python-exit-code 1 \
  --python scripts/export_web.py -- --output-dir /absolute/path/to/assets

Geometry is evaluated (including bevels, curves and text) and batched by
material. The saved Blender source is never modified. glTF uses metres, Y-up;
the car faces +Z and its four wheel groups rotate around their local X axes.
"""
from collections import defaultdict
from pathlib import Path
import argparse
import json
import math
import struct
import sys

import bpy
from mathutils import Matrix

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--output-dir', type=Path, default=ROOT / 'web' / 'assets')
args = parser.parse_args(sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else [])
args.output_dir.mkdir(parents=True, exist_ok=True)
scene = bpy.context.scene
scene.frame_set(1)
hero = next(o for o in scene.objects if o.name == 'Comet / hero turquoise coupe')
hero_objects = {hero, *hero.children_recursive}
original_objects = list(scene.objects)
hero.animation_data_clear()
hero.location = (0, 0, 0)
hero.rotation_euler = (0, 0, 0)
for wheel in hero.children:
    if 'wheel_radius' in wheel:
        wheel.animation_data_clear()
        wheel.rotation_euler = (0, 0, 0)
bpy.context.view_layer.update()
depsgraph = bpy.context.evaluated_depsgraph_get()
export_collection = bpy.data.collections.new('WEB_EXPORT_TEMPORARY')
scene.collection.children.link(export_collection)


def material_key(materials):
    return tuple(m.name if m else '' for m in materials)


def batch_objects(objects, prefix, parent=None):
    """Bake evaluated surfaces, preserving a local wheel pivot where requested."""
    groups = defaultdict(list)
    target_inverse = parent.matrix_world.inverted() if parent else Matrix.Identity(4)
    for obj in objects:
        if obj.type not in {'MESH', 'CURVE', 'FONT', 'SURFACE'}:
            continue
        evaluated = obj.evaluated_get(depsgraph)
        mesh = bpy.data.meshes.new_from_object(evaluated, preserve_all_data_layers=True, depsgraph=depsgraph)
        if not mesh or not mesh.polygons:
            if mesh:
                bpy.data.meshes.remove(mesh)
            continue
        mesh.transform(target_inverse @ obj.matrix_world)
        baked = bpy.data.objects.new(prefix + ' / ' + obj.name, mesh)
        export_collection.objects.link(baked)
        groups[material_key(mesh.materials)].append(baked)
    joined = []
    for key, group in groups.items():
        bpy.ops.object.select_all(action='DESELECT')
        for obj in group:
            obj.select_set(True)
        bpy.context.view_layer.objects.active = group[0]
        if len(group) > 1:
            bpy.ops.object.join()
        obj = bpy.context.view_layer.objects.active
        obj.name = prefix + ' / ' + (key[0].split(' / ')[-1] if key else 'surface')
        if parent:
            obj.parent = parent
            obj.matrix_parent_inverse = Matrix.Identity(4)
        joined.append(obj)
    return joined


def export_glb(path, objects):
    bpy.ops.object.select_all(action='DESELECT')
    for obj in objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    bpy.ops.export_scene.gltf(
        filepath=str(path), export_format='GLB', use_selection=True,
        export_yup=True, export_apply=False, export_animations=False,
        export_cameras=False, export_lights=False, export_extras=True,
        export_materials='EXPORT', export_normals=True, export_texcoords=False,
        export_tangents=False,
    )


# Static environment, including the two parked cars. Ocean, sun, and lighting
# are generated by the web renderer to keep dynamic water and sky inexpensive.
environment = [o for o in original_objects if o not in hero_objects
               and o.name not in {'Atlantic Ocean', 'Sunset / distant golden sun'}]
environment_batches = batch_objects(environment, 'Coast')
export_glb(args.output_dir / 'environment.glb', environment_batches)

# Five transform nodes preserve the car and wheel hierarchy. Meshes are batched
# within each transform node; the browser can rotate each complete wheel.
car_root = bpy.data.objects.new('Coastal GT', None)
export_collection.objects.link(car_root)
car_root['forward_axis'] = '+Z'
car_root['wheel_radius_m'] = 0.43
car_root['width'] = 2.36
car_root['length'] = 4.72
bpy.context.view_layer.update()
car_nodes = [car_root]
body = [o for o in hero.children if o.type == 'MESH']
car_nodes += batch_objects(body, 'Body', car_root)
wheel_names = []
for wheel in sorted((o for o in hero.children if 'wheel_radius' in o), key=lambda o: o.name):
    name = 'wheel_' + ('left' if wheel.location.x < 0 else 'right') + '_' + ('front' if wheel.location.y < 0 else 'rear')
    pivot = bpy.data.objects.new(name, None)
    export_collection.objects.link(pivot)
    pivot.parent = car_root
    pivot.location = wheel.location
    pivot['wheel_radius'] = float(wheel['wheel_radius'])
    pivot['roll_axis'] = 'X'
    bpy.context.view_layer.update()
    car_nodes.append(pivot)
    car_nodes += batch_objects(list(wheel.children), name, pivot)
    wheel_names.append(name)
export_glb(args.output_dir / 'car.glb', car_nodes)


def inspect_glb(path):
    raw = path.read_bytes()
    magic, version, length = struct.unpack_from('<4sII', raw)
    assert magic == b'glTF' and version == 2 and length == len(raw)
    json_length, json_type = struct.unpack_from('<I4s', raw, 12)
    assert json_type == b'JSON'
    doc = json.loads(raw[20:20 + json_length])
    assert doc.get('meshes') and doc.get('materials')
    assert not doc.get('animations')
    assert all('uri' not in entry for entry in doc.get('buffers', []))
    assert all('uri' not in entry for entry in doc.get('images', []))
    primitive_count = sum(len(m['primitives']) for m in doc['meshes'])
    vertex_count = 0
    triangle_count = 0
    for mesh in doc['meshes']:
        for primitive in mesh['primitives']:
            positions = doc['accessors'][primitive['attributes']['POSITION']]
            assert all(math.isfinite(v) for v in positions['min'] + positions['max'])
            vertex_count += positions['count']
            if 'indices' in primitive:
                triangle_count += doc['accessors'][primitive['indices']]['count'] // 3
    return {'bytes': len(raw), 'meshes': len(doc['meshes']),
            'draw_calls': primitive_count, 'vertices': vertex_count,
            'triangles': triangle_count,
            'node_names': [n.get('name', '') for n in doc.get('nodes', [])]}

results = {name: inspect_glb(args.output_dir / name) for name in ('environment.glb', 'car.glb')}
assert results['environment.glb']['bytes'] < 15 * 1024 * 1024
assert results['environment.glb']['draw_calls'] < 150
assert all(name in results['car.glb']['node_names'] for name in wheel_names)
metadata = {
    'source': 'Original Sunset Coast Blender scene',
    'coordinates': 'Y-up; car forward +Z; metres',
    'wheel_nodes': wheel_names,
    'wheel_radius': 0.43,
    'road': {'min_x': -6.5, 'max_x': 6.5, 'surface_y': 0},
    'beach': {'min_x': 11, 'max_x': 31, 'surface_y': -0.18},
    'ocean': {'min_x': 31, 'surface_y': -0.37},
    'playable_bounds': {'min_x': -5.3, 'max_x': 28, 'min_z': -450, 'max_z': 55},
    'assets': {name: {k: v for k, v in data.items() if k != 'node_names'} for name, data in results.items()},
}
(args.output_dir / 'scene-data.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
print('WEB_EXPORT_OK', json.dumps(metadata, ensure_ascii=False), flush=True)
